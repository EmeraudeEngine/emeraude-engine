namespace EmEn::PlatformSpecific
{
	std::optional< ApproximateLocation >
	approximateLocation () noexcept
	{
		DYNAMIC_TIME_ZONE_INFORMATION information{};

		if ( GetDynamicTimeZoneInformation(&information) == TIME_ZONE_ID_INVALID )
		{
			return std::nullopt;
		}

		const auto zone = convertWideToUTF8(std::wstring{static_cast< const wchar_t * >(information.TimeZoneKeyName)});

		if ( zone.empty() )
		{
			return std::nullopt;
		}

		/* The user's region (ISO 3166 two letters): "Romance Standard Time" is Brussels in BE, Paris by default. */
		std::string territory;
		std::array< wchar_t, 8 > iso{};

		if ( const auto nation = GetUserGeoID(GEOCLASS_NATION); nation != GEOID_NOT_AVAILABLE && GetGeoInfoW(nation, GEO_ISO2, iso.data(), static_cast< int >(iso.size()), 0) > 0 )
		{
			territory = convertWideToUTF8(std::wstring{iso.data()});
		}

		const WindowsZone * fallback = nullptr;

		for ( const auto & entry : WindowsZones )
		{
			if ( zone != entry.windowsZone )
			{
				continue;
			}

			if ( !territory.empty() && territory == entry.territory )
			{
				return ApproximateLocation{.latitude = entry.latitude, .longitude = entry.longitude, .source = zone + " (" + territory + ")"};
			}

			if ( std::string_view{entry.territory} == "001" )
			{
				fallback = &entry;
			}
		}

		if ( fallback == nullptr )
		{
			return std::nullopt;
		}

		return ApproximateLocation{.latitude = fallback->latitude, .longitude = fallback->longitude, .source = zone};
	}
}
